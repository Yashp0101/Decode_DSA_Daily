list = [2,1,3]
list.append(4) # Adds 4 to the end of the list
print(list)

list.sort() # Sorts the list in ascending order
print(list)

list.remove(1) # Removes 1 from the list
print(list)

list.insert(1, 5) # Inserts 5 at index 1
print(list)

list.pop(1) # Removes and returns the last item
print(list)
